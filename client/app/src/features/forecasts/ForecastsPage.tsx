/**
 * Forecasts — `/forecasts` (E.8, §30.8). Districts by risk band (real
 * `/dashboard/heatmap` rows) + the persisted forecast-kind insights (real
 * `/intelligence/workbench?kind=forecast`), each expanding to factors,
 * confidence decomposition, limitations and the §11 training-window caveat via
 * the standard InsightCard. Nothing fabricated; empty windows say so.
 */
import { useNavigate } from "react-router-dom";

import { useGeoDistricts, useInsights } from "@/api";
import { InsightCard } from "@/components/insight";
import { QueryBoundary } from "@/components/states";
import { RiskBand, TrustBadge } from "@/components/trust";
import { Panel } from "@/design/primitives";

/** Highest risk first; numeric scores live in each district's risk Insight. */
const BAND_ORDER = ["critical", "high", "medium", "low"] as const;

export default function ForecastsPage() {
  const navigate = useNavigate();
  const districts = useGeoDistricts();
  const forecasts = useInsights({ kind: "forecast", limit: 100 });

  return (
    <div className="min-h-0 flex-1 overflow-auto">
      <div className="mx-auto flex max-w-5xl flex-col gap-4 p-6">
        <header className="flex flex-col gap-1">
          <h1 className="font-display text-page-title text-ink-primary">Forecasts</h1>
          <TrustBadge context="forecast" />
        </header>

        <Panel className="p-4">
          <h2 className="mb-3 text-caption uppercase tracking-wide text-ink-muted">
            District risk bands
          </h2>
          <QueryBoundary
            query={districts}
            emptyMessage="No district risk has been computed for the current window."
            degradedMessage="District risk is unavailable — the prediction tables have not been computed yet."
            isEmpty={(d) => d.length === 0}
            skeletonLines={4}
          >
            {(rows) => (
              <div className="flex flex-col gap-1.5">
                {[...rows]
                  .sort(
                    (a, b) =>
                      BAND_ORDER.indexOf(a.risk_band) -
                      BAND_ORDER.indexOf(b.risk_band),
                  )
                  .map((d) => (
                    <button
                      key={d.district_id}
                      type="button"
                      onClick={() => navigate(`/geo?district=${d.district_id}`)}
                      className="flex items-center gap-3 rounded border border-line px-3 py-2 text-left hover:border-signal/40 hover:bg-raised"
                    >
                      <span className="min-w-0 flex-1 truncate text-body text-ink-primary">
                        {d.district_name}
                      </span>
                      <span className="font-mono text-caption text-ink-muted">
                        {d.case_count} cases
                      </span>
                      <RiskBand band={d.risk_band} />
                    </button>
                  ))}
              </div>
            )}
          </QueryBoundary>
        </Panel>

        <section className="flex flex-col gap-2">
          <h2 className="text-caption uppercase tracking-wide text-ink-muted">
            Forecast insights
          </h2>
          <QueryBoundary
            query={forecasts}
            emptyMessage="No forecast insights exist for the current window — they are generated by the prediction precompute."
            degradedMessage="The insight feed is unavailable."
            isEmpty={(d) => d.items.length === 0}
            skeletonLines={6}
          >
            {(d) => (
              <div className="flex flex-col gap-2">
                {d.items.map((i) => (
                  <InsightCard key={i.id} insight={i} />
                ))}
              </div>
            )}
          </QueryBoundary>
        </section>
      </div>
    </div>
  );
}
